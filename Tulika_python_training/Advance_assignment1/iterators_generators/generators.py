# Question 7: Process a large dataset using a generator.
def large_dataset_generator(limit: int) -> Generator[int, None, None]:
    """
    Simulate processing a large dataset by generating
    records one at a time instead of storing all records
    in memory.

    Args:
        limit (int): Number of records to generate.

    Yields:
        int: Individual record.
    """
    for record_id in range(1, limit + 1):
        yield record_id


def process_large_dataset(limit: int) -> None:
    """
    Process records generated by a generator.

    Args:
        limit (int): Number of records to process.
    """
    for record in large_dataset_generator(limit):
        print(f"Processing record {record}")


