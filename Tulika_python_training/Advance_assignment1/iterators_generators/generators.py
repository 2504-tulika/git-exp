"""
Generator examples.
"""
def get_positive_integer(prompt: str) -> int:
    """
    Get a valid positive integer from the user.
    """
    while True:
        try:
            value = int(input(prompt))

            if value <= 0:
                print("Please enter a positive integer.")
                continue

            return value

        except ValueError:
            print("Please enter a valid integer.")


# Question 3: Create a generator that yields square numbers up to N.

def square_generator(limit: int):
    """
    Generate square numbers up to N.
    """
    for number in range(1, limit + 1):
        yield number ** 2

# Question 4: Create a generator that yields Fibonacci numbers up to N.
def fibonacci_generator(limit: int):
    """
    Generate Fibonacci numbers.
    """
    first_number = 0
    second_number = 1

    for _ in range(limit):
        yield first_number
        first_number, second_number = (
            second_number,
            first_number + second_number
        )

# Question 5: Create a generator expression that yields even numbers from 1 to 50.
from typing import Generator
def generate_even_numbers() -> Generator[int, None, None]:
    """
    Generate even numbers from 1 to 50 using a generator expression.
    """
    return (
        number
        for number in range(1, 51)
        if number % 2 == 0
    )

